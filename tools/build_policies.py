#!/usr/bin/env python3
"""Generates every native policy artifact, Rego rules + tests, the 1:1 mapping matrix and sample plans from controls/definitions.py."""
import json, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "controls"))
from definitions import CONTROLS
import engine


def w(path, text):
    p = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8", newline="\n").write(text)


def js(o):
    return json.dumps(o, indent=2) + "\n"


def rp(attr):
    return "".join(f"[{s}]" if s.isdigit() else f'["{s}"]' for s in attr.split("."))


def rego(c):
    cid, n = c["id"], c["id"].split("-")[1]
    L = ["# GENERATED by tools/build_policies.py from controls/definitions.py. DO NOT EDIT.", f"# {cid} {c['title']} ({c['severity']})", f"package pac.c{n}", "", "import rego.v1", "",
         'changing(r) if {\n\tsome a in r.change.actions\n\ta in {"create", "update"}\n}', ""]
    for i, r in enumerate(c["tf"], 1):
        t, a, op, v = r["type"], r["attr"], r["op"], json.dumps(r["val"])
        P = f"a{rp(a)}"
        if t.startswith("provider:"):
            cl = t.split(":")[1]
            L += [f'deny contains msg if {{\n\tinput.configuration.provider_config["{cl}"]\n\tnot ok{i}\n\tmsg := "[{cid}] provider {cl}: {a} is not an approved value"\n}}',
                  f'ok{i} if {{\n\tinput.configuration.provider_config["{cl}"].expressions["{a}"].constant_value in {v}\n}}', ""]
            continue
        head = f'deny contains msg if {{\n\tsome r in input.resource_changes\n\tr.type == "{t}"\n\tchanging(r)\n'
        if op != "forbid":
            head += f"\tnot sat{i}(r.change.after)\n"
        L.append(head + f'\tmsg := sprintf("[{cid}] %s ({a})", [r.address])\n}}')
        has = f"has{i}(a) if {{\n\tv := {P}\n\tv != null\n\tv != \"\"\n\tv != []\n\tv != {{}}\n}}"
        if op == "eq":
            L.append(f"sat{i}(a) if {{\n\t{P} == {v}\n}}")
        elif op == "in":
            L.append(f"sat{i}(a) if {{\n\t{P} in {v}\n}}")
        elif op == "exists":
            L.append(f"sat{i}(a) if {{\n\thas{i}(a)\n}}\n{has}")
        elif op == "absent":
            L.append(f"sat{i}(a) if {{\n\tnot has{i}(a)\n}}\n{has}")
        elif op == "ne":
            L.append(f"sat{i}(a) if {{\n\tnot eq{i}(a)\n}}\neq{i}(a) if {{\n\t{P} == {v}\n}}")
        elif op == "not_contains":
            L.append(f"sat{i}(a) if {{\n\tnot has{i}(a)\n}}\nhas{i}(a) if {{\n\tsome x in {P}\n\tx == {v}\n}}")
        if r["miss"]:
            L.append(f"sat{i}(a) if {{\n\tnot def{i}(a)\n}}\ndef{i}(a) if {{\n\tv := {P}\n\tv != null\n}}")
        L.append("")
    return "\n".join(L) + "\n"


def rego_tests(c):
    n = c["id"].split("-")[1]
    L = ["# GENERATED from the same fixtures the Python oracle executes. DO NOT EDIT.", f"package pac.c{n}_test", "", "import rego.v1", "", f"import data.pac.c{n}", ""]
    for name, plan, exp in engine.fixtures(c):
        L.append(f"test_{re.sub(r'[^A-Za-z0-9_]', '_', name)} if {{\n\tcount(c{n}.deny) == {exp} with input as {json.dumps(plan)}\n}}\n")
    return "\n".join(L)


def azure(c):
    s = c["azure"]
    then = {"effect": "[parameters('effect')]"}
    if s.get("details"):
        then["details"] = s["details"]
    return {"properties": {"displayName": f"{c['id']} {c['title']}", "policyType": "Custom", "mode": s["mode"], "description": c["intent"],
            "metadata": {"category": "Policy-as-Code Baseline", "controlId": c["id"], "version": "1.0.0"},
            "parameters": {"effect": {"type": "String", "allowedValues": s["effects"], "defaultValue": s["default"], "metadata": {"displayName": "Effect"}}},
            "policyRule": {"if": s["rule"], "then": then}}}


def main():
    manifest, rows = [], []
    for c in CONTROLS:
        cid = c["id"]
        files = {"rego": f"policies/rego/{cid.lower().replace('-', '_')}.rego", "rego_test": f"policies/rego/{cid.lower().replace('-', '_')}_test.rego"}
        w(files["rego"], rego(c)); w(files["rego_test"], rego_tests(c))
        a = c["aws"]
        files["aws"] = f"policies/aws/{'scp' if a['kind'] == 'preventive' else 'config'}/{cid}.json"
        w(files["aws"], js(a["artifact"]))
        files["azure"] = f"policies/azure/{cid}.json"; w(files["azure"], js(azure(c)))
        g = c["gcp"]
        if g["kind"] == "preventive":
            files["gcp"] = f"policies/gcp/org-policy/{cid}.json"; w(files["gcp"], js(g["policy"]))
            files["gcp_dryrun"] = f"policies/gcp/org-policy/{cid}.dryrun.json"; w(files["gcp_dryrun"], js({"name": g["policy"]["name"], "dryRunSpec": g["policy"]["spec"]}))
        elif g["kind"] == "custom-constraint":
            art = dict(g["artifact"]); art["policyDryRun"] = {"name": art["policy"]["name"], "dryRunSpec": art["policy"]["spec"]}
            files["gcp"] = f"policies/gcp/custom-constraints/{cid}.json"; w(files["gcp"], js(art))
        else:
            files["gcp"] = f"policies/gcp/compensating/{cid}.json"; w(files["gcp"], js(g["artifact"]))
        manifest.append({"id": cid, "title": c["title"], "severity": c["severity"], "frameworks": c["fw"], "intent": c["intent"], "files": files,
                         "engines": {k: {"kind": c[k]["kind"], "fidelity": c[k]["fidelity"], "gap": c[k].get("gap", "")} for k in ("aws", "azure", "gcp")},
                         "rego_rules": len(c["tf"]), "fixtures": len(engine.fixtures(c))})
        ab = lambda k: f"{c[k]['kind']} / {c[k]['fidelity']}"
        rows.append(f"| {cid} | {c['title']} | {c['severity']} | {len(c['tf'])} rules | {ab('aws')} | {ab('azure')} | {ab('gcp')} |")
    w("controls/manifest.json", js(manifest))
    # AWS limits: max 5 SCPs per target and 5120 chars each -> first-fit pack all SCP statements into bundles
    stmts = [(c["id"], st) for c in CONTROLS if c["aws"]["kind"] == "preventive" for st in c["aws"]["artifact"]["Statement"]]
    size = lambda b: len(json.dumps({"Version": "2012-10-17", "Statement": [x for _, x in b]}, separators=(",", ":")))
    bundles = []
    for cid, st in stmts:
        for b in bundles:
            if size(b + [(cid, st)]) <= 4800:
                b.append((cid, st)); break
        else:
            bundles.append([(cid, st)])
    idx = []
    for i, b in enumerate(bundles, 1):
        f = f"policies/aws/scp/bundles/pac-bundle-{i}.json"
        w(f, js({"Version": "2012-10-17", "Statement": [x for _, x in b]}))
        idx.append({"file": f, "controls": sorted({c for c, _ in b}), "chars": size(b)})
    w("controls/bundles.json", js(idx))
    fid = {}
    for m in manifest:
        for e in m["engines"].values():
            fid[e["fidelity"]] = fid.get(e["fidelity"], 0) + 1
    w("docs/mapping-matrix.md", "# 1:1 control mapping matrix (generated)\n\nEvery control exists in all four engines. Fidelity is stated honestly: **full** = same enforcement semantics, **partial** = same intent with a documented gap, **compensating** = no native preventive equivalent, so a detective or structural control is used.\n\n"
      "| ID | Control | Severity | OPA/Rego (Terraform plan) | AWS (SCP / Config) | Azure Policy | GCP Org Policy |\n|---|---|---|---|---|---|---|\n" + "\n".join(rows) +
      f"\n\nFidelity totals across {len(manifest)*3} cloud-native mappings: " + ", ".join(f"{k} {v}" for k, v in sorted(fid.items())) + ".\n\n## Documented gaps\n\n" +
      "\n".join(f"- **{m['id']} {e}**: {d['gap']}" for m in manifest for e, d in m["engines"].items() if d["gap"]) + "\n\n## Framework mapping (indicative, GRC review pending)\n\n| ID | NIST 800-53 | CIS v8 | ISO 27001:2022 |\n|---|---|---|---|\n" +
      "\n".join(f"| {m['id']} | {', '.join(m['frameworks']['NIST 800-53'])} | {', '.join(m['frameworks']['CIS v8'])} | {', '.join(m['frameworks']['ISO 27001'])} |" for m in manifest) + "\n")
    good = {"resource_changes": [], "configuration": {"provider_config": {}}}
    bad = {"resource_changes": [], "configuration": {"provider_config": {}}}
    after = {}
    for c in CONTROLS:
        for r in c["tf"]:
            if r["type"].startswith("provider:"):
                cl = r["type"].split(":")[1]
                good["configuration"]["provider_config"][cl] = {"expressions": {r["attr"]: {"constant_value": r["val"][0]}}}
            elif r["op"] not in ("forbid", "absent"):
                engine.set_path(after.setdefault(r["type"], {}), r["attr"], engine.pass_val(r))
    for t, a in after.items():
        good["resource_changes"].append({"address": f"{t}.compliant", "type": t, "change": {"actions": ["create"], "after": a}})
    for c in CONTROLS:
        for name, plan, exp in engine.fixtures(c):
            if exp:
                for r in plan["resource_changes"]:
                    r = dict(r); r["address"] = f"{c['id'].lower()}.{name}"[:90]; bad["resource_changes"].append(r)
                bad["configuration"]["provider_config"].update(plan.get("configuration", {}).get("provider_config", {}))
    w("examples/plan-compliant.json", js(good)); w("examples/plan-noncompliant.json", js(bad))
    print(f"built {len(CONTROLS)} controls, {sum(m['fixtures'] for m in manifest)} fixtures")


if __name__ == "__main__":
    main()
